/**
 * Result formatting: turn a RunResult into a "tool return value".
 *
 * The spec requires returning: the local image path, whether it succeeded, a short explanation,
 * and key metadata. On top of that it has to be **clickable** inside DSH — which is why the
 * absolute path sits on a line of its own with no decoration, so the DSH frontend recognises it
 * as a file reference (verified: a bare absolute path is rendered as a file link).
 */
import type { RunResult } from './runner.js'
import { PLUGIN_VERSION } from './runner.js'

/** The normalized return value of generate_image, matching the structure declared in output.schema. */
export interface ImageToolResult {
  text: string
  /** Absolute path of the primary output file (first, so the frontend can spot it). */
  path: string
  files: string[]
  mode: string
  seed: number
  width: number
  height: number
  steps: number
  cfg_scale: number
  strength: number
  model: string
  sampler: string
  scheduler: string
  prompt_id: string
  comfy_url: string
  duration_ms: number
  success: boolean
  mode_inferred: boolean
  metadata_path?: string
  notes: string[]
}

const MODE_LABELS: Record<string, string> = {
  text2img: 'text-to-image',
  img2img: 'image-to-image',
  inpaint: 'inpainting',
  remove_background: 'background removal'
}

/**
 * Compose the text shown to the model.
 *
 * Note the order: the **absolute path goes on its own line first** (`Image: <path>`),
 * and only then the parameter description. Even a quick scan will not miss the path.
 */
export function renderResultText(result: ImageToolResult): string {
  const label = MODE_LABELS[result.mode] ?? result.mode
  const lines: string[] = []

  lines.push(`✅ Image generated (${label}${result.mode_inferred ? ', mode inferred automatically' : ''})`)
  lines.push('')
  lines.push(`Image: ${result.path}`)
  if (result.metadata_path) lines.push(`Metadata: ${result.metadata_path}`)
  lines.push('')
  lines.push(
    `Params: seed=${result.seed} size=${result.width}x${result.height} steps=${result.steps} ` +
      `cfg=${result.cfg_scale}${result.mode === 'img2img' || result.mode === 'inpaint' ? ` strength=${result.strength}` : ''}`
  )
  lines.push(`Checkpoint: ${result.model}`)
  lines.push(
    `Sampling: ${result.sampler} / ${result.scheduler}  Elapsed: ${(result.duration_ms / 1000).toFixed(1)} s`
  )
  lines.push(`ComfyUI: ${result.comfy_url} (prompt_id=${result.prompt_id})`)
  if (result.notes.length > 0) {
    lines.push('')
    lines.push('Notes:')
    for (const note of result.notes) lines.push(`  - ${note}`)
  }
  lines.push('')
  lines.push(
    'Tip: to reproduce the same image, call again with the same seed; to fine-tune it, change the prompt and use a new seed.'
  )
  return lines.join('\n')
}

/** RunResult → tool return value. */
export function formatResult(run: RunResult): ImageToolResult {
  const primary = run.outputPaths[0] ?? ''
  const value: ImageToolResult = {
    text: '',
    path: primary,
    files: [...run.outputPaths],
    mode: run.mode,
    seed: run.request.seed,
    width: run.request.width,
    height: run.request.height,
    steps: run.request.steps,
    cfg_scale: run.request.cfgScale,
    strength: run.request.strength,
    model: run.checkpoint,
    sampler: run.samplerName,
    scheduler: run.scheduler,
    prompt_id: run.promptId,
    comfy_url: run.comfyUrl,
    duration_ms: run.durationMs,
    success: true,
    mode_inferred: run.modeInferred,
    notes: run.notes.length > 0 ? run.notes : [`Generated by dsh-comfyui-image v${PLUGIN_VERSION}`]
  }
  if (run.metadataPath) value.metadata_path = run.metadataPath
  value.text = renderResultText(value)
  return value
}

/**
 * The text shown to the model on failure.
 * Spec requirement: "ComfyUI not started / input file missing / workflow failed" must all be clear.
 */
export function renderFailureText(error: unknown, mode: string): string {
  const label = MODE_LABELS[mode] ?? mode
  const message = error instanceof Error ? error.message : String(error)
  const hint =
    error && typeof error === 'object' && 'hint' in error
      ? String((error as { hint?: unknown }).hint ?? '')
      : ''
  const lines = [`❌ Image generation failed (${label})`, '', message]
  if (hint) {
    lines.push('')
    lines.push(hint)
  }
  return lines.join('\n')
}
